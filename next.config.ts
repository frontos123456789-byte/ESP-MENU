import type { NextConfig } from "next";
const dev = process.env.NODE_ENV !== "production";
// Next.js hydration needs inline scripts and React sets inline style attributes,
// so 'unsafe-inline' stays; everything else is locked to this origin.
// connect-src allows https: because the optional DNS test queries random
// subdomains of the operator's own probe zone, and ipify / ipwho.is are external.
const csp = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${dev ? " 'unsafe-eval'" : ""}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self' data:",
  `connect-src 'self' https:${dev ? " ws: wss: http:" : ""}`,
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join("; ");
const config: NextConfig = {
  poweredByHeader: false,
  async headers() {
    return [
      {
        source: "/:path*",
        headers: [
          { key: "Content-Security-Policy", value: csp },
          { key: "Referrer-Policy", value: "no-referrer" },
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "X-Frame-Options", value: "DENY" },
          { key: "Cross-Origin-Opener-Policy", value: "same-origin" },
          // Camera, microphone and geolocation are never used by this page.
          // Sensors are intentionally NOT blocked so Permissions API reports the real state.
          {
            key: "Permissions-Policy",
            value: "camera=(), microphone=(), geolocation=()",
          },
          { key: "Cache-Control", value: "no-store" },
        ],
      },
    ];
  },
};
export default config;
